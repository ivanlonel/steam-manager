"""The rows an answer becomes, and what the loader finds while it turns one into them."""

from collections import Counter, defaultdict
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from typing import TYPE_CHECKING, Final, cast

if TYPE_CHECKING:
    from collections.abc import Collection

    from pydantic import BaseModel
    from sqlalchemy import Table

    from steam_manager.db.schema import SteamBase

_EPOCH: Final = datetime(1970, 1, 1)  # noqa: DTZ001  # the notebook's dates are naive UTC text
_EMPTY: Final[tuple[object, ...]] = (None, (), [], {})


class Rows:
    """Rows to write, per table, each checked against the table's columns as it is added."""

    def __init__(self) -> None:
        """Start with no rows."""
        self.tables: defaultdict[str, list[dict[str, object]]] = defaultdict(list)
        """The rows of each table, by table name, in the order they were added."""

    def add(self, table: type[SteamBase], /, **values: object) -> None:
        r"""
        Add one row; the columns it leaves out are blank.

        :param table: The table the row goes to.
        :param \*\*values: The row's values, by column name.
        :raise ValueError: When a column isn't the table's, or is one SQLite generates; or when
            a column that can't be blank is, which makes the answer malformed.
        """
        declared = cast("Table", table.__table__)
        name = declared.name
        for column in values:
            if column not in declared.columns:
                message = f"{name} has no column {column}"
                raise ValueError(message)
            if declared.columns[column].computed is not None:
                message = f"{name}.{column} is generated by SQLite"
                raise ValueError(message)
        if missing := [
            column.name
            for column in declared.columns
            if not column.nullable
            and column is not declared.autoincrement_column
            and values.get(column.name) is None
        ]:
            message = f"{name} needs {', '.join(missing)}"
            raise ValueError(message)
        self.tables[name].append(values)

    def extend(self, other: Rows) -> None:
        """
        Add every row of *other*, after the rows already here.

        :param other: Rows built apart.
        """
        for name, rows in other.tables.items():
            self.tables[name].extend(rows)


@dataclass
class Findings:
    """The two reports a healthy load leaves empty."""

    unknown: Counter[str] = field(default_factory=Counter)
    """Fields Steam sent that nothing stores, by path, such as ``extra_details.new``."""
    mismatches: Counter[str] = field(default_factory=Counter)
    """Values left out as derivable, by name, with how often they didn't follow; a name that
    always followed counts 0."""

    def rest(self, model: BaseModel | None, path: str, used: Collection[str]) -> None:
        """
        Report every field of *model*, declared or not, that the loader didn't use.

        ``None``, ``[]`` and ``{}`` are placeholders Steam sends and aren't reported, as the
        notebooks skipped them; ``""`` is a value and is.

        :param model: A part of an answer, or ``None`` when Steam didn't send it.
        :param path: Where the part sits in the answer, such as ``extra_details.metacritic``.
        :param used: The declared fields the loader stored, checked or deliberately skipped.
        :raise ValueError: When *used* names a field the model doesn't declare.
        """
        if model is None:
            return
        declared = type(model).model_fields
        if wrong := sorted(set(used) - declared.keys()):
            message = f"{path} has no field {', '.join(wrong)}"
            raise ValueError(message)
        left = {name: getattr(model, name) for name in declared if name not in used}
        left |= model.model_extra or {}
        for name, value in left.items():
            if value not in _EMPTY:
                self.unknown[f"{path}.{name}"] += 1

    def same(self, name: str, stored: object, derived: object) -> None:
        """
        Check a value left out as derivable against its derivation.

        :param name: What is checked, such as ``visible``.
        :param stored: What Steam sent.
        :param derived: What the database derives in its place.
        """
        self.mismatches[name] += stored != derived

    def update(self, other: Findings) -> None:
        """
        Add *other*'s counts to these.

        :param other: Findings gathered apart.
        """
        self.unknown.update(other.unknown)
        self.mismatches.update(other.mismatches)


def iso(seconds: int | None) -> str | None:
    """
    Turn epoch seconds into a date as the notebook stores it: UTC text without a zone.

    :param seconds: The seconds Steam sent; 0 means no date.
    :return: Text such as ``2011-04-12 00:00:00``, or ``None``.
    """
    return str(_EPOCH + timedelta(seconds=seconds)) if seconds else None
